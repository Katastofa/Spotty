// ЗАПАС. Жёсткое окно уже, чем измеренное, на SPOTTY_LIMIT_MARGIN_DEG.
// ВАЖНО: измеренные JOINT_MIN_US/JOINT_MAX_US сами получены как «подвод до
// касания, затем отступ 3° внутрь» (CALIBRATION.md). Значит суммарный отступ
// от точки касания рамы составляет 3 + 3 = 6°. Это сознательно: остаточная
// ошибка нуля у девяти каналов из двенадцати не измерена и может достигать
// половины зуба шлица 25T, то есть ±7.2° (см. «РЕВИЗИЯ НУЛЕЙ» выше).
//
// Менять SPOTTY_LIMIT_MARGIN_DEG в сторону уменьшения — только после того,
// как M9_ПРОТОКОЛ.md заполнен на все двенадцать строк.
// ===========================================================================

static constexpr float    SPOTTY_LIMIT_MARGIN_DEG = 3.0f;
static constexpr uint16_t SPOTTY_MARGIN_US =
    (uint16_t)(SPOTTY_LIMIT_MARGIN_DEG * SPOTTY_US_PER_DEG + 0.5f);   // 17 мкс

// Канал считается рабочим, только если ВСЕ четыре таблицы его признают.
// Любая одиночная дырка (нуль, предел, знак) выключает канал целиком —
// это защита от полузаполненной таблицы, а не строгость ради строгости.
constexpr bool spottyChUsed(uint8_t ch) {
  return ch < 16
      && JOINT_SIGN[ch]    != 0
      && JOINT_ZERO_US[ch] != 0
      && JOINT_MIN_US[ch]  != 0
      && JOINT_MAX_US[ch]  != 0;
}

// Нижняя жёсткая граница канала, мкс. Не уже абсолютного окна серво.
constexpr uint16_t spottyHardLoUs(uint8_t ch) {
  return !spottyChUsed(ch) ? SPOTTY_ABS_MIN_US
       : (uint16_t)((JOINT_MIN_US[ch] + SPOTTY_MARGIN_US) < SPOTTY_ABS_MIN_US
                    ? SPOTTY_ABS_MIN_US
                    : (JOINT_MIN_US[ch] + SPOTTY_MARGIN_US));
}

// Верхняя жёсткая граница канала, мкс.
constexpr uint16_t spottyHardHiUs(uint8_t ch) {
  return !spottyChUsed(ch) ? SPOTTY_ABS_MAX_US
       : (uint16_t)((int)(JOINT_MAX_US[ch] - SPOTTY_MARGIN_US) > (int)SPOTTY_ABS_MAX_US
                    ? SPOTTY_ABS_MAX_US
                    : (JOINT_MAX_US[ch] - SPOTTY_MARGIN_US));
}

// --------------------------- кламп в мкс -----------------------------------
// Возвращает значение, которое РАЗРЕШЕНО отправить в серво. hit (если задан)
// становится true, когда вход пришлось урезать: это не норма, а признак
// ошибки в вызывающем коде, и вызывающий обязан на него отреагировать.
inline uint16_t spottyClampUs(uint8_t ch, long us, bool *hit = 0) {
  if (ch >= 16) { if (hit) *hit = true; return SPOTTY_ABS_MIN_US; }
  long lo = (long)spottyHardLoUs(ch);
  long hi = (long)spottyHardHiUs(ch);
  if (lo > hi) { long t = lo; lo = hi; hi = t; }        // вывернутая строка таблицы
  long out = us < lo ? lo : (us > hi ? hi : us);
  if (out < (long)SPOTTY_ABS_MIN_US) out = SPOTTY_ABS_MIN_US;
  if (out > (long)SPOTTY_ABS_MAX_US) out = SPOTTY_ABS_MAX_US;
  if (hit && out != us) *hit = true;
  return (uint16_t)out;
}

// --------------------------- кламп в градусах -------------------------------
// Пределы сустава в градусах ножной системы, выведенные из ЖЁСТКОГО окна.
//   us = zero + sign * angle * k   =>   angle = (us - zero) / (sign * k)
inline void spottyAngleLimits(uint8_t ch, float &lo, float &hi) {
  if (!spottyChUsed(ch)) { lo = 0.0f; hi = 0.0f; return; }
  const float k = JOINT_SIGN[ch] * SPOTTY_US_PER_DEG;
  const float a = ((float)spottyHardLoUs(ch) - (float)JOINT_ZERO_US[ch]) / k;
  const float b = ((float)spottyHardHiUs(ch) - (float)JOINT_ZERO_US[ch]) / k;
  lo = a < b ? a : b;
  hi = a < b ? b : a;
}

// Кламп ЦЕЛИ ДО расчёта импульса. Это рубеж номер один: он не даёт углу
// уехать за предел и тем самым убивает windup в генераторе траектории.
// Порог 0.05° — чтобы дрожание последнего бита float не считалось выходом.
inline float spottyClampAngle(uint8_t ch, float deg, bool *hit = 0) {
  float lo, hi;
  spottyAngleLimits(ch, lo, hi);
  if (!spottyChUsed(ch)) { if (hit) *hit = true; return 0.0f; }
  if (deg < lo) { if (hit && (lo - deg) > 0.05f) *hit = true; return lo; }
  if (deg > hi) { if (hit && (deg - hi) > 0.05f) *hit = true; return hi; }
  return deg;
}

// Угол -> импульс БЕЗ клампа. Отдельно от клампа намеренно: любой вызов
// этой функции обязан пройти через spottyClampUs перед записью в драйвер.
inline float spottyAngleToUsRaw(uint8_t ch, float deg) {
  return (float)JOINT_ZERO_US[ch] + JOINT_SIGN[ch] * deg * SPOTTY_US_PER_DEG;
}

// Полный путь угол -> разрешённый импульс. Оба рубежа сразу.
inline uint16_t spottyAngleToUs(uint8_t ch, float deg, bool *hit = 0) {
  const float safe = spottyClampAngle(ch, deg, hit);
  return spottyClampUs(ch, (long)(spottyAngleToUsRaw(ch, safe) + 0.5f), hit);
}

// ===========================================================================
// ПРОВЕРКИ ТАБЛИЦ НА ЭТАПЕ КОМПИЛЯЦИИ
// Ошибка в таблице не должна доживать до серво. Скетч с вывернутой строкой
// просто не соберётся.
// ===========================================================================
#define SPOTTY_CHECK_CH(ch)                                                    \
  static_assert(!spottyChUsed(ch) || JOINT_MIN_US[ch] >= SPOTTY_ABS_MIN_US,    \
                "ch" #ch ": MIN ниже абсолютного окна серво");                 \
  static_assert(!spottyChUsed(ch) || JOINT_MAX_US[ch] <= SPOTTY_ABS_MAX_US,    \
                "ch" #ch ": MAX выше абсолютного окна серво");                 \
  static_assert(!spottyChUsed(ch) ||                                           \
                JOINT_MIN_US[ch] + 2 * SPOTTY_MARGIN_US < JOINT_MAX_US[ch],    \
                "ch" #ch ": запас съел весь ход сустава");                     \
  static_assert(!spottyChUsed(ch) ||                                           \
                (JOINT_ZERO_US[ch] > spottyHardLoUs(ch) &&                     \
                 JOINT_ZERO_US[ch] < spottyHardHiUs(ch)),                      \
                "ch" #ch ": нуль вне жёсткого окна канала");                   \
  static_assert(!spottyChUsed(ch) ||                                           \
                (JOINT_SIGN[ch] == 1 || JOINT_SIGN[ch] == -1),                 \
                "ch" #ch ": знак не +1 и не -1")

SPOTTY_CHECK_CH(0);  SPOTTY_CHECK_CH(1);  SPOTTY_CHECK_CH(2);  SPOTTY_CHECK_CH(3);
SPOTTY_CHECK_CH(4);  SPOTTY_CHECK_CH(5);  SPOTTY_CHECK_CH(6);  SPOTTY_CHECK_CH(7);
SPOTTY_CHECK_CH(8);  SPOTTY_CHECK_CH(9);  SPOTTY_CHECK_CH(10); SPOTTY_CHECK_CH(11);
SPOTTY_CHECK_CH(12); SPOTTY_CHECK_CH(13); SPOTTY_CHECK_CH(14); SPOTTY_CHECK_CH(15);

// Карта каналов не должна ссылаться на выключенный канал и не должна
// использовать один канал дважды. Проверяется в рантайме, см. ниже:
// на этапе компиляции цикл по двумерной карте в C++11 не выражается.

// -------------------- проверки целостности при компиляции -------------------
static_assert(SPOTTY_ABS_MIN_US < SPOTTY_ABS_MAX_US, "окно вывернуто");
static_assert(SPOTTY_MARGIN_US > 0, "запас обнулился");
static_assert(SPOTTY_US_PER_DEG > 0.0f, "масштаб серво неположителен");

