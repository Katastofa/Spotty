/*
 * ПЕЧАТЬ САМОПРОВЕРКИ — через SPOTTY_LOG, а не напрямую в Serial.
 * Добавлено 2026-08-31 вместе с веб-панелью. По умолчанию SPOTTY_LOG И ЕСТЬ
 * Serial, поэтому servo_hold и servo_calib ведут себя ровно как раньше.
 * gait_test с включённым SPOTTY_WEB определяет SPOTTY_LOG как LOG (Serial
 * плюс кольцевой буфер), чтобы «ТАБЛИЦЫ НЕ ПРОШЛИ» было видно и в браузере,
 * а не только в мониторе порта. Значений калибровки это не касается вовсе.
 */
#ifndef SPOTTY_LOG
#define SPOTTY_LOG Serial
#endif

#ifdef ARDUINO
inline bool spottyLimitsSelfCheck(bool verbose = true) {
  int bad = 0;
  uint8_t seen[16];
  for (uint8_t i = 0; i < 16; i++) seen[i] = 0;

  for (uint8_t leg = 0; leg < LEG_COUNT; leg++) {
    for (uint8_t j = 0; j < JOINT_PER_LEG; j++) {
      uint8_t ch = SPOTTY_CH[leg][j];
      if (ch >= 16) { SPOTTY_LOG.printf("КАРТА: нога %u сустав %u -> канал %u вне 0..15\n", leg, j, ch); bad++; continue; }
      if (!spottyChUsed(ch)) { SPOTTY_LOG.printf("КАРТА: нога %u сустав %u -> ch%u выключен таблицами\n", leg, j, ch); bad++; continue; }
      if (seen[ch]++) { SPOTTY_LOG.printf("КАРТА: ch%u назначен более одного раза\n", ch); bad++; }
    }
  }

  for (uint8_t ch = 0; ch < 16; ch++) {
    if (!spottyChUsed(ch)) continue;
    uint16_t lo = spottyHardLoUs(ch), hi = spottyHardHiUs(ch);
    bool ok = (lo < hi) && (JOINT_ZERO_US[ch] > lo) && (JOINT_ZERO_US[ch] < hi);
    if (!ok) bad++;
    if (verbose || !ok) {
      float alo, ahi; spottyAngleLimits(ch, alo, ahi);
      SPOTTY_LOG.printf("ch%-2u  измер %4u..%4u  жёстк %4u..%4u  нуль %4u  знак %+d  углы %7.1f..%7.1f  %s\n",
                    ch, JOINT_MIN_US[ch], JOINT_MAX_US[ch], lo, hi,
                    JOINT_ZERO_US[ch], JOINT_SIGN[ch], alo, ahi, ok ? "ok" : "ОШИБКА ТАБЛИЦЫ");
    }
  }

  if (bad) SPOTTY_LOG.printf("САМОПРОВЕРКА ПРЕДЕЛОВ НЕ ПРОЙДЕНА: %d замечани(й). ШИМ запрещён.\n", bad);
  else     SPOTTY_LOG.printf("Самопроверка пределов пройдена. Запас внутрь от измеренного: %.1f° (%u мкс).\n",
                         SPOTTY_LIMIT_MARGIN_DEG, SPOTTY_MARGIN_US);
  return bad == 0;
}
#endif  // ARDUINO
